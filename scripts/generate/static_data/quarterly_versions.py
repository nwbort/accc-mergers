"""Version numbers for the quarterly report — ``data/processed/quarterly_versions.json``.

A quarter's report is not frozen when the quarter ends. Late register changes
(a refused waiver re-filed weeks later, a re-dated determination) and the
pre-notification estimates, which firm up as later case numbers are issued,
keep moving a published quarter's figures. A reader holding last month's PDF
needs to be able to tell it apart from today's, so every quarter carries a
version, with the Sydney date that version first appeared:

- **Major** (``v1``, ``v2``, …): anything a reader would notice changed — a
  count, a rate, a median, a sentence, a milestone, a Tribunal matter.
- **Minor** (``v2.1``, ``v2.2``, …): only the histograms moved. The usual
  cause is a pre-notification estimate being refined as the waivers lodged
  around it are decided and reach the register, nudging one matter a few days
  across a bar boundary while the quarter's median, average and p90 stay put.
  A histogram shift big enough to move those is a major version anyway.

A new major version starts its minor count again, and a version with no minor
part is written plainly (``v2``, never ``v2.0``).

The store keeps each quarter's history, newest last, as
``{"version", "date", "digest", "major_digest"}``. ``digest`` hashes the
quarter's block in ``quarterly.json`` (less the version fields themselves);
``major_digest`` hashes it with the histograms' bucket counts left out too. So
a version moves exactly when what the page and the PDF show moves, and a
regeneration that changes nothing changes nothing here. Redrawing the PDF with
new layout code is not a new version: the version tracks the figures and
words, not their typesetting.

Written by ``generate_static_data`` and committed by the pipeline, like
``phase1_estimates.json``. :func:`stamp_versions` is pure; the load/save pair
around it is the production path.
"""

import hashlib
import json
from datetime import datetime
from zoneinfo import ZoneInfo

from scripts.paths import REPO_ROOT

VERSIONS_STORE_PATH = REPO_ROOT / "data" / "processed" / "quarterly_versions.json"

#: Fields stamped onto each block by :func:`stamp_versions`, and therefore left
#: out of the digest that decides them.
VERSION_FIELDS = ("version", "version_date")

_SYDNEY = ZoneInfo("Australia/Sydney")

_STORE_COMMENT = (
    "Generated by scripts/generate/static_data/quarterly_versions.py; committed by "
    "the pipeline. One history per quarter (keyed as the page URL names it, 26Q3), "
    "newest last: a new version is recorded whenever the quarter's block in "
    "quarterly.json changes, minor (2.1) if only its histograms moved, else major (3). "
    "Delete a quarter's entry to restart it at v1. Entries carrying 'commit' and "
    "'change' were backfilled by hand from the git history of the quarter's PDF, "
    "from before versioning began (a redraw that only changed layout was not counted)."
)


#: The histograms' bucket counts, as paths into a quarter's block. A change
#: confined to these is a minor version.
HISTOGRAM_PATHS = (
    ("notifications", "timing", "buckets"),
    ("waivers", "timing", "buckets"),
    ("pre_notification", "buckets"),
)


def _digest(content: dict) -> str:
    encoded = json.dumps(content, sort_keys=True, separators=(",", ":"), ensure_ascii=False)
    return hashlib.sha256(encoded.encode("utf-8")).hexdigest()[:16]


def block_digest(block: dict) -> str:
    """A stable hash of what a quarter's report says, version fields aside."""
    return _digest({k: v for k, v in block.items() if k not in VERSION_FIELDS})


def major_digest(block: dict) -> str:
    """:func:`block_digest` with the histograms' bucket counts left out too."""
    content = json.loads(json.dumps({k: v for k, v in block.items() if k not in VERSION_FIELDS}))
    for *parents, leaf in HISTOGRAM_PATHS:
        node = content
        for key in parents:
            node = node.get(key) if isinstance(node, dict) else None
        if isinstance(node, dict):
            node.pop(leaf, None)
    return _digest(content)


def parse_version(version) -> tuple[int, int]:
    """``"2.1"`` → ``(2, 1)``; ``"2"`` or ``2`` → ``(2, 0)``."""
    major, _, minor = str(version).partition(".")
    return int(major), int(minor or 0)


def format_version(major: int, minor: int) -> str:
    """``(2, 0)`` → ``"2"``, ``(2, 1)`` → ``"2.1"``: no ``.0`` on a major version."""
    return f"{major}.{minor}" if minor else str(major)


def stamp_versions(payload: dict, store: dict, today: str) -> dict:
    """Stamp ``version`` and ``version_date`` on every quarter in ``payload``.

    ``store`` is the history as loaded. A quarter whose block no longer matches
    its latest recorded digest (or that has none) gets a new version dated
    ``today`` (``YYYY-MM-DD``): minor if only the histograms moved, else major.
    Returns the updated store, holding only the quarters ``payload``
    publishes. Neither argument is mutated except the payload's blocks.
    """
    updated = {}
    for block in payload.get("quarters", []):
        key = block["url_key"]
        history = list(store.get(key) or [])
        digest, major = block_digest(block), major_digest(block)
        latest = history[-1] if history else None
        if latest is None:
            history.append({"version": "1", "date": today, "digest": digest, "major_digest": major})
        elif latest.get("digest") != digest:
            number, minor = parse_version(latest["version"])
            # A recorded major digest that still matches means only the
            # histograms moved. One that is missing (a backfilled entry)
            # can't vouch for that, so the change counts as major.
            if latest.get("major_digest") == major:
                version = format_version(number, minor + 1)
            else:
                version = format_version(number + 1, 0)
            history.append({"version": version, "date": today, "digest": digest, "major_digest": major})
        block["version"] = history[-1]["version"]
        block["version_date"] = history[-1]["date"]
        updated[key] = history
    return updated


def load_store() -> dict:
    """Load the version history, or an empty dict if absent or unreadable."""
    try:
        with open(VERSIONS_STORE_PATH, encoding="utf-8") as f:
            data = json.load(f)
    except FileNotFoundError:
        return {}
    except (json.JSONDecodeError, OSError) as e:
        print(f"Warning: could not load {VERSIONS_STORE_PATH}: {e}")
        return {}
    return {k: v for k, v in data.items() if not k.startswith("_")}


def save_store(store: dict) -> None:
    """Persist the version history, quarters in order, with a comment."""
    VERSIONS_STORE_PATH.parent.mkdir(parents=True, exist_ok=True)
    payload = {"_comment": _STORE_COMMENT}
    # 26Q1 < 26Q2 < 27Q1 sorts correctly as text: two-digit year first.
    for key in sorted(store):
        payload[key] = store[key]
    with open(VERSIONS_STORE_PATH, "w", encoding="utf-8") as f:
        json.dump(payload, f, indent=2)
        f.write("\n")


def apply_versions(payload: dict, today: str | None = None) -> dict:
    """Production path: load the store, stamp ``payload``, save the store."""
    today = today or datetime.now(_SYDNEY).date().isoformat()
    store = stamp_versions(payload, load_store(), today)
    save_store(store)
    return payload
